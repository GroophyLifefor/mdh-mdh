export function icon(name: string, size = 16) {
  const r = +(size / 15).toFixed(4); // rem, so icons follow the size setting
  return `<svg class="ico" style="width:${r}rem;height:${r}rem" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] ?? ''}</svg>`;
}

/** Fills every <i data-icon="name"> in the page. */
export function hydrateIcons(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((el) => {
    el.innerHTML = icon(el.dataset.icon!, Number(el.dataset.size) || 16);
  });
}
